#!/usr/bin/env node
"use strict";
/*
 * Bundles the modules in src/ into the single main.js that Obsidian loads.
 * No dependencies: it only wraps each file so `require("./name")` finds the other modules.
 *
 *   node scripts/build.js           write main.js
 *   node scripts/build.js --check   exit 1 if main.js is out of date (used by the tests and CI)
 */
const fs = require("fs");
const path = require("path");
const { minify } = require("./minify.js");
const { mangleModule } = require("./mangle.js");

const root = path.join(__dirname, "..");
const srcDir = path.join(root, "src");
const vendorDir = path.join(root, "vendor");
const ENTRY = "main";

const jsFiles = (dir) => fs.readdirSync(dir).filter((f) => f.endsWith(".js"));

// Sources check out as CRLF on Windows and LF everywhere else. The bundle
// embeds them verbatim, so it must not depend on that: otherwise the
// committed main.js matches only the platform it was built on, and the
// up-to-date-build test (and release CI with it) fails on the other one.
const readLf = (file) => fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n");

/**
 * The project MIT text and the third-party notices, wrapped in one comment.
 * Obsidian installs only main.js, so the notice has to travel inside it.
 */
function bundledNotices() {
  const read = (name) => readLf(path.join(root, name)).trim();
  const body = ["MCQ Tracker license", "", read("LICENSE"), "", "Third-party notices", "", read("NOTICES.md")]
    .join("\n")
    .replace(/\*\//g, "*\\/")
    .split("\n")
    .map((line) => (line ? ` * ${line}` : " *"))
    .join("\n");
  return `/*\n${body}\n */\n`;
}

function build() {
  const files = new Map(jsFiles(srcDir).map((f) => [f.replace(/\.js$/, ""), path.join(srcDir, f)]));
  if (fs.existsSync(vendorDir)) {
    for (const file of jsFiles(vendorDir)) files.set(`vendor/${file.replace(/\.js$/, "")}`, path.join(vendorDir, file));
  }
  const ids = [...files.keys()].sort((a, b) => {
    if (a === ENTRY) return 1;
    if (b === ENTRY) return -1;
    return a < b ? -1 : a > b ? 1 : 0;
  });
  let out = `"use strict";
/*
 * MCQ Tracker - Obsidian plugin.
 * THIS FILE IS GENERATED by scripts/build.js from the modules in src/.
 * Edit those, then run \`npm run build\`.
 */
${bundledNotices()}const __defs = Object.create(null);
const __cache = Object.create(null);
function __load(id) {
  if (__cache[id]) return __cache[id].exports;
  const module = (__cache[id] = { exports: {} });
  __defs[id](module, module.exports, __require);
  return module.exports;
}
function __require(name) {
  if (name.startsWith("../vendor/")) return __load("vendor/" + name.slice("../vendor/".length).replace(/\.js$/, ""));
  return name.startsWith("./") ? __load(name.slice(2).replace(/\.js$/, "")) : require(name);
}
`;
  for (const id of ids) {
    const file = files.get(id);
    const vendored = id.startsWith("vendor/");
    let code = minify(readLf(file));
    if (!vendored) {
      const mangled = mangleModule(code);
      if (mangled.bailed) console.warn(`build: ${id} ships minified-only (${mangled.bailed})`);
      code = mangled.code;
    }
    code = code.replace(/^"use strict";/, "");
    out += `\n__defs[${JSON.stringify(id)}] = function (module, exports, require) {\n${code}\n};\n`;
  }
  out += `\nmodule.exports = __load(${JSON.stringify(ENTRY)});\n`;
  return out;
}

module.exports = { build };

if (require.main === module) {
  const target = path.join(root, "main.js");
  const next = build();
  if (process.argv.includes("--check")) {
    const cur = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
    if (cur !== next) {
      console.error("main.js is out of date. Run `npm run build` and commit the result.");
      process.exit(1);
    }
    console.log("main.js is up to date.");
  } else {
    fs.writeFileSync(target, next);
    console.log(`Wrote main.js (${next.length} bytes from ${jsFiles(srcDir).length + (fs.existsSync(vendorDir) ? jsFiles(vendorDir).length : 0)} modules).`);
  }
}
