#!/usr/bin/env node
"use strict";
/*
 * Bundles the modules in src/ into the single main.js that Obsidian loads.
 * No dependencies: it only wraps each file so `require("./name")` finds the other modules.
 *
 *   node scripts/build.js           write main.js
 *   node scripts/build.js --check   exit 1 if main.js is out of date (used by the tests and CI)
 */
const fs = require("fs");
const path = require("path");

const root = path.join(__dirname, "..");
const srcDir = path.join(root, "src");
const ENTRY = "main";

const jsFiles = (dir) => fs.readdirSync(dir).filter((f) => f.endsWith(".js"));

function build() {
  const files = new Map(jsFiles(srcDir).map((f) => [f.replace(/\.js$/, ""), path.join(srcDir, f)]));
  const ids = [...files.keys()].sort((a, b) => (a === ENTRY ? 1 : b === ENTRY ? -1 : a.localeCompare(b)));
  let out = `"use strict";
/*
 * MCQ Tracker - Obsidian plugin.
 * THIS FILE IS GENERATED by scripts/build.js from the modules in src/.
 * Edit those, then run \`npm run build\`.
 */
const __defs = Object.create(null);
const __cache = Object.create(null);
function __load(id) {
  if (__cache[id]) return __cache[id].exports;
  const module = (__cache[id] = { exports: {} });
  __defs[id](module, module.exports, __require);
  return module.exports;
}
function __require(name) {
  return name.startsWith("./") ? __load(name.slice(2).replace(/\\.js$/, "")) : require(name);
}
`;
  for (const id of ids) {
    const code = fs.readFileSync(files.get(id), "utf8").replace(/^"use strict";\n/, "").trimEnd();
    out += `\n/* ---- ${path.relative(root, files.get(id)).replace(/\\/g, "/")} ---- */\n__defs[${JSON.stringify(id)}] = function (module, exports, require) {\n${code}\n};\n`;
  }
  out += `\nmodule.exports = __load(${JSON.stringify(ENTRY)});\n`;
  return out;
}

module.exports = { build };

if (require.main === module) {
  const target = path.join(root, "main.js");
  const next = build();
  if (process.argv.includes("--check")) {
    const cur = fs.existsSync(target) ? fs.readFileSync(target, "utf8") : "";
    if (cur !== next) {
      console.error("main.js is out of date. Run `npm run build` and commit the result.");
      process.exit(1);
    }
    console.log("main.js is up to date.");
  } else {
    fs.writeFileSync(target, next);
    console.log(`Wrote main.js (${next.length} bytes from ${jsFiles(srcDir).length} modules).`);
  }
}
